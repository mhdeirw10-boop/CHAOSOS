'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const base = path.join(__dirname, '..');
const window = {};
vm.runInNewContext(fs.readFileSync(path.join(base, 'js/appCatalog.js'), 'utf8'), { window });
const catalog = window.VoidAppCatalog;
assert.ok(catalog, 'catalog initializes');
assert.ok(catalog.apps.length >= 24, 'catalog covers the OS apps and supporting pages');
assert.equal(catalog.byPath('apps/void-discovery/index.html').id, 'void-discovery');
assert.ok(catalog.search('كاميرا').some(app => app.id === 'void-camera'));
assert.ok(catalog.search('VoidBrowserX').some(app => app.id === 'void-browserx'));
assert.ok(catalog.search('صلاحيات').some(app => app.id === 'void-manager'));
const links = catalog.externalLinks('VoidTube');
assert.ok(links.some(link => link.provider === 'Google Play' && link.url.startsWith('https://play.google.com/')));
assert.ok(links.every(link => /^https:\/\//.test(link.url)));
console.log('PASS: app catalog metadata, Arabic search, aliases, and safe external search URLs');
