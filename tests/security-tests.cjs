const start=layer.indexOf('function safeCalc('), end=layer.indexOf('function execute(',start);
assert.ok(start>=0&&end>start,'shared calculator parser must exist');
vm.runInContext(layer.slice(start,end)+';globalThis.testCalc=safeCalc;',context);
assert.equal(context.testCalc('(12+3)*4'),60);
assert.equal(context.testCalc('2+2'),4);
assert.throws(()=>context.testCalc('1/0'));
assert.throws(()=>context.testCalc('globalThis.process.exit()'));
const opened=[];
window.CHAOS={open(app){opened.push(app);return{ok:true,message:'opened '+app}},evaluateMath:context.testCalc,execute(command){return{ok:true,message:'saved '+command}}};
