const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const base = path.join(__dirname, '..');
const memory = new Map();
const localStorage = {getItem:k=>memory.has(k)?memory.get(k):null,setItem:(k,v)=>memory.set(k,String(v)),removeItem:k=>memory.delete(k)};
const window = {};
const document = {readyState:'complete',querySelector:()=>null,addEventListener(){}};
const context = vm.createContext({window, localStorage, URL, console, Date, TextEncoder, document, CustomEvent:function CustomEvent(type,options){this.type=type;this.detail=options?.detail;}});
for (const file of ['policy.js','input.js','storage.js','index.js']) vm.runInContext(fs.readFileSync(path.join(base,'js/brain/security',file),'utf8'),context,{filename:file});
