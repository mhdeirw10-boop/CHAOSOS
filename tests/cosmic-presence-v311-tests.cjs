const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const base = path.join(__dirname, '..');
const handlers = new Map();
const window = { localStorage: { getItem: () => null, setItem: () => {} }, document: { addEventListener: (name, fn) => handlers.set(name, fn) } };
window.window = window;
const ctx = vm.createContext({ window, Math, Number, String, Object, Array, Promise, Set, JSON });
vm.runInContext(fs.readFileSync(path.join(base, 'js/brain/voice/chaosPresenceAudio.js'), 'utf8'), ctx, { filename: 'chaosPresenceAudio.js' });
const api = window.CHAOSPresenceAudio;
assert.equal(api.version, '3.1.1-experimental');
assert.equal(api.status().localOnly, true);
assert.equal(api.status().networkUsed, false);
assert.equal(api.status().prerecordedAudio, false);
assert.equal(api.status().available, false);
for (const event of ['chaosai:presence','chaosai:ready','chaosai:thinking','chaosai:warning','chaosai:idle']) assert.ok(handlers.has(event), `kernel event contract: ${event}`);
api.play('unknown').then(result => assert.equal(result.code, 'UNKNOWN_PRESENCE_CUE')); 
assert.equal(api.speakRare('').code, 'EMPTY_TEXT');
assert.equal(api.stop().ok, true);
const html = fs.readFileSync(path.join(base, 'apps/chaosai-center/index.html'), 'utf8');
for (const id of ['cosmicAwaken', 'cosmicThink', 'cosmicWarn', 'cosmicPulse', 'cosmicRelease', 'cosmicStop']) assert.match(html, new RegExp(`id="${id}"`));
assert.match(html, /chaosPresenceAudio\.js/);
assert.match(fs.readFileSync(path.join(base, 'sw.js'), 'utf8'), /chaosPresenceAudio\.js/);
console.log('PASS: cosmic presence API contracts, local-only flags, invalid cue handling, UI wiring, and cache wiring');
